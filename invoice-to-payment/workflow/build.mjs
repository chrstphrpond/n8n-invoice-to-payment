// Generates the invoicing workflow set:
//   workflow/issue-invoices.json   CRIT · Issue invoices          (critInvoiceIssue)
//   workflow/match-payments.json   CRIT · Match payments          (critPaymentMatch)
//   workflow/chase-invoices.json   CRIT · Chase overdue invoices  (critInvoiceChase)
//   workflow/manifest.json         what the kit's harness and validator read
//   workflow/layout.json           nodes (name, type, section, position, note) and connections, for drawing
//   node invoice-to-payment/workflow/build.mjs           write
//   node invoice-to-payment/workflow/build.mjs --check   fail if a file on disk is stale
// Logic lives in workflow/lib/*.js (unit tested) and is inlined into the Code nodes; flows/*.mjs only wire nodes.
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { writeOrCheck } from '../../_shared/lib/build-output.mjs';
import * as chase from './flows/chase.mjs';
import * as issue from './flows/issue.mjs';
import * as payments from './flows/payments.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const FLOWS = [issue, payments, chase];
export const ENV_VARS = [
  'BILLING_WEBHOOK_SECRET', 'PAYMENTS_WEBHOOK_SECRET',
  'PDF_BASE_URL', 'PDF_API_TOKEN', 'STORAGE_BASE_URL', 'STORAGE_TOKEN', 'STORAGE_BUCKET',
  'EMAIL_BASE_URL', 'EMAIL_API_KEY', 'EMAIL_FROM', 'EMAIL_TIMEOUT_MS',
  'PAYMENTS_BASE_URL', 'PAYMENTS_API_KEY', 'REVIEW_SLACK_CHANNEL',
  'INVOICE_CLOCK_OVERRIDE', 'INVOICE_SCHEDULES',
];

export const MANIFEST = {
  slug: 'invoice-to-payment',
  workflows: FLOWS.map(flow => flow.ENTRY),
  env: ENV_VARS,
};

const shortType = type => type.replace(/^n8n-nodes-base\./, '');

// The section a node sits in: the numbered sticky whose rectangle holds the node's position.
export function layoutOf(workflow) {
  const stickies = workflow.nodes.filter(node => node.type === 'n8n-nodes-base.stickyNote');
  const sections = stickies.filter(node => /^\d+\. /.test(node.name)).map(node => ({
    name: node.name, position: node.position, width: node.parameters.width, height: node.parameters.height,
    text: node.parameters.content.split('\n').slice(1).join(' ').trim(),
  }));
  const sectionOf = ([x, y]) => sections.find(s => x >= s.position[0] && x <= s.position[0] + s.width && y >= s.position[1] && y <= s.position[1] + s.height)?.name ?? null;
  const nodes = workflow.nodes.filter(node => node.type !== 'n8n-nodes-base.stickyNote').map(node => ({
    name: node.name, type: shortType(node.type), section: sectionOf(node.position), position: node.position, note: node.notes,
    ...(node.onError === 'continueErrorOutput' ? { error_output: true } : {}),
  }));
  const connections = [];
  for (const [from, outputs] of Object.entries(workflow.connections)) {
    (outputs.main ?? []).forEach((links, output) => {
      const node = workflow.nodes.find(candidate => candidate.name === from);
      const kind = node.onError === 'continueErrorOutput' && output === 1 ? 'error' : 'main';
      for (const link of links ?? []) connections.push({ from, output, to: link.node, kind });
    });
  }
  return { id: workflow.id, name: workflow.name, sections, nodes, connections };
}

export function buildAll() {
  const files = {};
  const layouts = [];
  for (const flow of FLOWS) {
    const workflow = flow.build();
    files[flow.FILE] = workflow;
    layouts.push({ file: flow.FILE, ...layoutOf(workflow) });
  }
  files['manifest.json'] = MANIFEST;
  files['layout.json'] = {
    note: 'Generated by workflow/build.mjs from the workflow JSON: every node with its section, canvas position and the note shown under it, and every connection (kind error = the node\'s error output).',
    workflows: layouts,
  };
  return files;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeOrCheck(here, buildAll(), process.argv.includes('--check'));
}
